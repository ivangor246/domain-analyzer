import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url))
const defaultOutput = path.resolve(scriptDirectory, '../src/api/generated.ts')

function option(name, fallback) {
  const index = process.argv.indexOf(name)
  return index === -1 ? fallback : process.argv[index + 1]
}

async function readStdin() {
  const chunks = []
  for await (const chunk of process.stdin) {
    chunks.push(chunk)
  }
  return Buffer.concat(chunks).toString('utf8')
}

async function readDocument(input) {
  if (input === '-') {
    return JSON.parse(await readStdin())
  }

  if (input.startsWith('http://') || input.startsWith('https://')) {
    const response = await globalThis.fetch(input)
    if (!response.ok) {
      throw new Error(`Unable to download OpenAPI document: HTTP ${response.status}`)
    }
    return response.json()
  }

  return JSON.parse(await readFile(input, 'utf8'))
}

function referenceName(reference) {
  return decodeURIComponent(reference.split('/').at(-1))
}

function propertyName(name) {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)
}

function literal(value) {
  return typeof value === 'string' ? JSON.stringify(value) : String(value)
}

function unique(values) {
  return [...new Set(values)]
}

function union(values) {
  const members = unique(values.filter(Boolean))
  if (members.length === 0) {
    return 'unknown'
  }
  if (members.length === 1) {
    return members[0]
  }
  return members.join(' | ')
}

function schemaType(schema, indent = 0) {
  if (!schema || typeof schema !== 'object') {
    return 'unknown'
  }

  if (schema.$ref) {
    return addNullable(`components['schemas'][${JSON.stringify(referenceName(schema.$ref))}]`, schema)
  }

  if (schema.const !== undefined) {
    return literal(schema.const)
  }

  const alternatives = schema.oneOf ?? schema.anyOf
  if (Array.isArray(alternatives)) {
    return addNullable(union(alternatives.map((item) => schemaType(item, indent))), schema)
  }

  if (Array.isArray(schema.allOf)) {
    return addNullable(schema.allOf.map((item) => schemaType(item, indent)).join(' & '), schema)
  }

  if (Array.isArray(schema.enum)) {
    return addNullable(union(schema.enum.map(literal)), schema)
  }

  if (Array.isArray(schema.type)) {
    return addNullable(union(schema.type.map((type) => schemaType({ type }, indent))), schema)
  }

  if (schema.type === 'array' || schema.items) {
    return addNullable(`Array<${schemaType(schema.items, indent)}>`, schema)
  }

  if (schema.type === 'object' || schema.properties || schema.additionalProperties !== undefined) {
    return addNullable(objectType(schema, indent), schema)
  }

  const primitiveTypes = {
    string: 'string',
    integer: 'number',
    number: 'number',
    boolean: 'boolean',
    null: 'null',
  }
  return addNullable(primitiveTypes[schema.type] ?? 'unknown', schema)
}

function addNullable(type, schema) {
  if (schema?.nullable !== true || type.includes('null')) {
    return type
  }
  return `${type} | null`
}

function objectType(schema, indent) {
  const properties = schema.properties ?? {}
  const required = new Set(schema.required ?? [])
  const entries = Object.entries(properties)
  const additionalProperties = schema.additionalProperties

  if (entries.length === 0) {
    if (additionalProperties === false) {
      return 'Record<string, never>'
    }
    if (additionalProperties && typeof additionalProperties === 'object') {
      return `Record<string, ${schemaType(additionalProperties, indent)}>`
    }
    return 'Record<string, unknown>'
  }

  const nextIndent = ' '.repeat(indent + 2)
  const closingIndent = ' '.repeat(indent)
  const lines = ['{']
  for (const [name, property] of entries) {
    const optional = required.has(name) ? '' : '?'
    lines.push(`${nextIndent}${propertyName(name)}${optional}: ${schemaType(property, indent + 2)};`)
  }
  lines.push(`${closingIndent}}`)
  return lines.join('\n')
}

function generate(document) {
  const schemas = document.components?.schemas
  if (!schemas || typeof schemas !== 'object') {
    throw new Error('OpenAPI document does not contain components.schemas')
  }

  const lines = [
    '// This file is generated by scripts/generate-api-types.mjs. Do not edit it manually.',
    '',
    'export interface components {',
    '  schemas: {',
  ]

  for (const name of Object.keys(schemas).sort()) {
    lines.push(`    ${propertyName(name)}: ${schemaType(schemas[name], 4)};`)
  }

  lines.push('  }', '}', '')
  return lines.join('\n')
}

const input = option('--input', process.env.OPENAPI_INPUT ?? 'http://localhost:8000/api/docs.json')
const output = option('--output', process.env.OPENAPI_OUTPUT ?? defaultOutput)
const checkOnly = process.argv.includes('--check')
const document = await readDocument(input)
const generated = generate(document)

if (checkOnly) {
  const current = await readFile(output, 'utf8').catch(() => null)
  if (current !== generated) {
    throw new Error(`Generated API types are out of date: ${path.relative(process.cwd(), output)}`)
  }
  console.log(`API types are up to date: ${path.relative(process.cwd(), output)}`)
} else {
  await writeFile(output, generated, 'utf8')
  console.log(`Generated ${path.relative(process.cwd(), output)}`)
}
